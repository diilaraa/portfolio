// Regenerates src/content/techIcons.ts from the simple-icons package (CC0).
// Run: node scripts/gen-tech-icons.mjs
import * as si from "simple-icons";
import { writeFileSync } from "node:fs";

const slugs = ["python", "dotnet", "react", "nextdotjs", "typescript", "flask", "opencv", "scikitlearn", "jira", "postman", "git"];

const luminance = (hex) => {
  const c = [0, 2, 4].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255).map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));
  return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
};

const icons = slugs.map((slug) => {
  const icon = si[`si${slug[0].toUpperCase()}${slug.slice(1)}`];
  if (!icon) throw new Error(`Missing icon: ${slug}`);
  // Light brand colors (e.g. React cyan) sit on a dark tile so the mark stays visible.
  const contrastOnWhite = 1.05 / (luminance(icon.hex) + 0.05);
  return { slug, title: icon.title, hex: `#${icon.hex}`, path: icon.path, darkTile: contrastOnWhite < 2.5 };
});

const body = `/** Generated by scripts/gen-tech-icons.mjs from simple-icons (CC0). Do not edit by hand. */
export type TechIcon = { slug: string; title: string; hex: string; path: string; darkTile: boolean };

export const techIcons: TechIcon[] = ${JSON.stringify(icons, null, 2)};
`;
writeFileSync("src/content/techIcons.ts", body);
